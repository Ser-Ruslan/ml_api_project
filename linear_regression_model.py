import numpy as np


class LinearRegressionModel:
    """
    Класс для имитации модели машинного обучения линейной регрессии.
    """
    
    def __init__(self):
        """
        Инициализация модели с заданными коэффициентами регрессии.
        """
        self.b0 = 48.6  # количество баллов по ИС
        self.b1 = 2     # оценка по ИС
        self.b2 = 45.9 / 50  # количество баллов по Python / 50
    
    def predict(self, x: np.ndarray) -> float:
        """
        Применяет модель линейной регрессии к входным данным.
        
        Args:
            x: numpy массив с тремя элементами [x0, x1, x2]
               x0 - признак для b0
               x1 - признак для b1 
               x2 - признак для b2
               
        Returns:
            float: предсказанное значение
        """
        if len(x) != 3:
            raise ValueError("Входной массив должен содержать ровно 3 элемента")
        
        # Вычисление линейной регрессии: y = b0*x0 + b1*x1 + b2*x2
        result = self.b0 * x[0] + self.b1 * x[1] + self.b2 * x[2]
        return float(result)
